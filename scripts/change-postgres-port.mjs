import {readFile,lstat,rename,writeFile,unlink} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {randomUUID} from 'node:crypto';
import net from 'node:net';
import {flags,privateDirectory,privateNewFile} from './backup-support.mjs';

const args=flags(process.argv.slice(2),['--port']);
if(!args['--port']||!/^\d+$/.test(args['--port']))throw Error('Specify --port with a local TCP port');
const port=Number(args['--port']);if(!Number.isSafeInteger(port)||port<1024||port>65535)throw Error('Port must be between 1024 and 65535');
const exec=promisify(execFile),rootFile=resolve('.local/postgres-runtime.json'),files=[rootFile,...['business','backup','migration'].map(name=>resolve('.local/postgres-'+name+'.json'))];
const original=JSON.parse(await readFile(rootFile,'utf8'));
if(original.host!=='127.0.0.1'||!Number.isInteger(original.port)||!original.tenants)throw Error('Only the configured loopback PostgreSQL runtime is supported');
const oldPort=original.port;if(port===oldPort){console.log(JSON.stringify({changed:false,port}));process.exit(0);}
const binary=join(process.env.LOCALAPPDATA,'IDMS/runtime/pgsql/bin/pg_ctl.exe'),data=join(process.env.LOCALAPPDATA,'IDMS/runtime/postgres-data');
if((await readFile(join(data,'PG_VERSION'),'utf8')).trim()!=='16')throw Error('Expected the existing PostgreSQL 16 cluster; refusing reconfiguration');
try{await exec(binary,['status','-D',data],{windowsHide:true});throw Error('Stop the owned PostgreSQL runtime before changing ports');}
catch(e){if(e.code!==3)throw e;}
async function free(p){
 if(process.platform==='win32'){
  const {stdout}=await exec('powershell.exe',['-NoProfile','-Command',`@(Get-NetTCPConnection -LocalPort ${p} -ErrorAction SilentlyContinue).Count`],{windowsHide:true});
  if(Number(stdout.trim())!==0)throw Error('A required Windows TCP endpoint is already bound; choose an unoccupied port');
 }
 await new Promise((ok,fail)=>{const s=net.createServer();s.once('error',()=>fail(Error('A required port is occupied; do not displace other processes')));s.listen({host:'127.0.0.1',port:p,exclusive:true},()=>s.close(ok));});}
for(const p of [port,4010,8081,4016])await free(p);
const changes=[];
for(const file of files){
 let raw;try{const stat=await lstat(file);if(!stat.isFile()||stat.isSymbolicLink())throw Error('Configuration must be a regular private file');raw=await readFile(file);}catch(e){if(e.code==='ENOENT'&&file!==rootFile)continue;throw e;}
 const value=JSON.parse(raw.toString('utf8'));if(value.host!==original.host||value.port!==oldPort)throw Error('Configuration endpoint disagreement; refusing partial reconfiguration');
 changes.push({file,raw,updated:Buffer.from(JSON.stringify({...value,port}))});
}
const rollback=resolve('.local','postgres-port-change-'+randomUUID());await privateDirectory(rollback);
for(let i=0;i<changes.length;i++)await privateNewFile(join(rollback,i+'.json'),changes[i].raw);
await privateNewFile(join(rollback,'manifest.json'),JSON.stringify({oldPort,newPort:port,files:changes.map(c=>c.file),createdAt:new Date().toISOString()}));
const completed=[];
try{
 for(const c of changes){const temp=c.file+'.'+randomUUID()+'.tmp';await privateNewFile(temp,c.updated);try{await rename(temp,c.file);}catch(e){await unlink(temp).catch(()=>{});throw e;}completed.push(c);}
}catch(e){for(const c of completed.reverse()){const temp=c.file+'.rollback-'+randomUUID();await privateNewFile(temp,c.raw);await rename(temp,c.file);}throw e;}
console.log(JSON.stringify({changed:true,host:original.host,oldPort,newPort:port,configurationFiles:changes.length,rollbackDirectory:rollback,credentialsLogged:false,databasesMoved:false,workflowConfig:'Regenerated by platform:start before launch',next:'Run postgres:setup, back up business databases, then platform:start'}));
